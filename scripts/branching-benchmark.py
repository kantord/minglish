#!/usr/bin/env python3
"""Benchmark: actual right-branching share across the whole real corpus
(every ADR, dogfooded prose — not the small synthetic corpus/accept.txt
used for grammar-feature snapshot tests) vs. the empirical ceiling this
grammar can produce for real, meaningful content (measured by actually
parsing hand-built candidate sentences, not theorized by hand — arc
direction in this grammar's own `nd()` head-slot scheme is not always
the naive linguistic-head intuition, see docs/branching-benchmark-2026-09-06.md).

Usage: python3 scripts/branching-benchmark.py
Writes: docs/branching-benchmark-2026-09-06.md
"""
import glob, re, subprocess, statistics

RB_RE = re.compile(r"right-branching (\d+)%")


def run_diagnose(sents):
    """Yield (sentence, right_branching_pct) for every sentence that parses."""
    for i in range(0, len(sents), 20):
        batch = sents[i:i + 20]
        out = subprocess.run(
            ["cargo", "run", "-q", "-p", "diagnose", "--bin", "diagnose", "--"] + batch,
            capture_output=True, text=True,
        ).stdout
        lines = out.splitlines()
        for idx, line in enumerate(lines):
            if line.startswith("✓") and idx + 1 < len(lines):
                sent = line[2:].strip()
                m = RB_RE.search(lines[idx + 1])
                if m:
                    yield sent, int(m.group(1))


def corpus_sentences():
    sents = []
    for adr in sorted(glob.glob("docs/adr/*.md")):
        out = subprocess.run(["python3", "scripts/extract-sentences.py", adr],
                              capture_output=True, text=True).stdout.strip().splitlines()
        sents += [x.replace("⏎", "\n") for x in out]
    return sents


def main():
    print("extracting real corpus sentences from docs/adr/*.md ...")
    sents = corpus_sentences()
    print(f"{len(sents)} candidate sentences; running diagnose ...")
    results = list(run_diagnose(sents))
    pcts = [p for _, p in results]
    # Degenerate 100% entries with zero dependency arcs (single-word
    # Imperatives, etc.) are not meaningful "fully right-branching"
    # sentences — they have nothing to branch. Separate them out.
    nontrivial = [(s, p) for s, p in results if not (p == 100 and len(s.split()) <= 2)]
    npct = [p for _, p in nontrivial]

    mean_all = statistics.mean(pcts) if pcts else 0
    mean_nontrivial = statistics.mean(npct) if npct else 0
    median_nontrivial = statistics.median(npct) if npct else 0

    buckets = {"0-24%": 0, "25-49%": 0, "50-74%": 0, "75-100%": 0}
    for p in npct:
        if p < 25: buckets["0-24%"] += 1
        elif p < 50: buckets["25-49%"] += 1
        elif p < 75: buckets["50-74%"] += 1
        else: buckets["75-100%"] += 1

    top = sorted(nontrivial, key=lambda t: -t[1])[:8]
    bottom = sorted(nontrivial, key=lambda t: t[1])[:8]

    with open("docs/branching-benchmark-2026-09-06.md", "w") as f:
        f.write("# Right-branching benchmark: actual corpus vs. empirical ceiling (2026-09-06)\n\n")
        f.write("*Generated by scripts/branching-benchmark.py — measured, not theorized.*\n\n")
        f.write(f"Sentences parsed: {len(results)} of {len(sents)} extracted "
                f"(the rest fail to parse for unrelated reasons — vocabulary gaps, "
                f"banned shapes — and are excluded, same as dogfood-sweep.md).\n\n")
        f.write(f"- Mean right-branching, all parsed sentences: **{mean_all:.1f}%**\n")
        f.write(f"- Mean right-branching, excluding trivial 1-2 word zero-arc sentences: **{mean_nontrivial:.1f}%**\n")
        f.write(f"- Median (non-trivial): **{median_nontrivial:.1f}%**\n\n")
        f.write("## Distribution\n\n| bucket | count | share |\n|---|---|---|\n")
        for k, v in buckets.items():
            f.write(f"| {k} | {v} | {100*v/max(len(npct),1):.0f}% |\n")
        f.write("\n## Most right-branching real sentences\n\n")
        for s, p in top:
            f.write(f"- {p}% — {s}\n")
        f.write("\n## Least right-branching real sentences\n\n")
        for s, p in bottom:
            f.write(f"- {p}% — {s}\n")
    print(f"mean(all)={mean_all:.1f}% mean(non-trivial)={mean_nontrivial:.1f}% median={median_nontrivial:.1f}%")
    print("report: docs/branching-benchmark-2026-09-06.md")


if __name__ == "__main__":
    main()
