run "the files are big"
echo
run "the agent deleted 3 file"
run "the agent deleted 3 files"
echo
run "the agent stopped"
run "the agent stopped the process"
echo '```'
echo
echo "## The repair loop: ambiguity and its fix"
echo
echo '```'
run "the agent stores the report in the database with the tool"
run "the agent opened the report with the tool" "the agent stores the report in the database"
echo '```'
echo
echo "Before/after translation previews with costs live in docs/cost-report.md"
echo "and docs/dogfood-cost-report.md."
} > "$OUT"
echo "showcase written to $OUT"
